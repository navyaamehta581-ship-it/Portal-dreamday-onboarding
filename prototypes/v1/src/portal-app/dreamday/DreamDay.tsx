import {Sparkles} from 'lucide-react';
import type {ChampionReview,ReviewItem} from '../../../../../contracts/activation/v1/handoff';
import {Origin,STATUS,Section} from '../../review/Editors';
import {navigate} from '../router';
import type {DreamDaySession} from './useDreamDay';

const STATUS_LABEL:Record<ChampionReview['status'],[string,string]>={not_submitted:['Not published yet',''],revising:['Not published yet',''],submitted:['Not published yet',''],
 resubmitted:['Not published yet',''],changes_requested:['Not published yet',''],approved:['Finalized','green'],published:['Published to your team','green'],
 published_before_dream_day:['Published before Dream Day','']};
const ACTION:Record<string,string>={edited:'Changed by',submitted:'Sent by',resubmitted:'Sent again by',withdrawn:'Withdrawn by',changes_requested:'Sent back by',approved:'Finalized by',published:'Published by'};
const ERRORS:Record<string,string>={CHAMPION_REQUIRED:'Your account can’t open Dream Day.'};

/** Dream Day: the Champion's optional look at the onboarding plan Chris published. A readable overview of the goals and
 * milestones first, the supporting context one click away. Nothing here needs approving: developers already have the
 * plan. Priorities and recommendations live in Team overview. Everything shown comes from the server's Champion view. */
export function DreamDay({dd,customer}:{dd:DreamDaySession;customer:string}){
 const v=dd.view;
 if(!v)return <div className="pt-empty" role={dd.error?'alert':'status'}><div><h2>{dd.error?(ERRORS[dd.error.code]??`Dream Day isn’t available (${dd.error.code}).`):'Loading Dream Day…'}</h2></div></div>;
 const suggestion=v.analysis==='model'?'AI suggestion':'Rule-based suggestion';
 const [label,tone]=STATUS_LABEL[v.status];
 const problems=v.plan?[v.plan.problem,...(v.plan.moreProblems??[])].filter(p=>p.summary||p.challenges.length):[];
 return <div className="pt-review" aria-label="Dream Day">
  <section className="pt-card" aria-label="Dream Day review">
   <div className="pt-card-head"><h3><Sparkles size={18} aria-hidden="true" style={{verticalAlign:'-3px',marginRight:8}}/>Your team’s onboarding plan</h3><span className={'pt-pill '+tone}>{label}</span></div>
   <p className="pt-note">The goals and milestones Chris prepared for {customer}. Your developers already see them and choose what to work on; nothing here needs your approval. Spotify’s solutions engineers handle repositories, docs and sign-in setup.</p>
   <Status v={v}/>
   {v.plan&&<div className="pt-actions"><button className="pt-btn sm" onClick={()=>navigate('/champion/team')}>Set priorities and recommend opportunities</button></div>}
   {v.history.length>0&&<History v={v}/>}
  </section>
  {v.plan&&<>
   {v.analysis==='rule_based_fallback'&&<div className="pt-banner warn" role="status">This plan was drafted by rule-based analysis because the AI model wasn’t available. It was not generated by the model.</div>}
   {v.plan.withheld>0&&<div className="pt-banner warn" role="status">{v.plan.withheld} item(s) were left out because they contained information you may not receive.</div>}
   <PlanOverview plan={v.plan} problems={problems.length} stakeholders={v.plan.stakeholders.length}/>
   <Section id="dd-goals" title="Technical goals" count={v.plan.goals.length} defaultOpen summary="What the onboarding aims for.">
    <ReadItems title="" items={v.plan.goals} suggestion={suggestion} empty="No goals yet."/>
   </Section>
   <Section id="dd-milestones" title="Onboarding milestones" count={v.plan.milestones.length} defaultOpen summary="Engineering outcomes developers can choose. A suggested owner is only a suggestion.">
    <MilestoneList plan={v.plan}/>
   </Section>
   <Section id="dd-questions" title="Clarification questions" count={v.plan.questions.length} summary="Open questions, not facts.">
    <ReadItems title="" items={v.plan.questions} suggestion={suggestion} empty="No open questions."/>
   </Section>
   <p className="pt-label" style={{marginTop:6}}>Supporting context</p>
   <Section id="dd-problems" title="Engineering problems" count={problems.length} summary="What the customer described, with challenges, systems and open points.">
    {problems.map((p,i)=><div key={i} className="pt-problem" aria-label={`Engineering problem ${i+1}`}>
     <p style={{marginTop:8}}><strong>Problem {i+1}.</strong> {p.summary}</p>
     <ReadItems title="Challenges" items={p.challenges} suggestion={suggestion}/>
     <ReadItems title="Relevant systems and workflows" items={p.systems} suggestion={suggestion}/>
     {(p.contradictions.length+p.unknowns.length)>0&&<details className="pt-details"><summary>Open points ({p.contradictions.length+p.unknowns.length})</summary>
      <ReadItems title="Contradictions" items={p.contradictions} suggestion={suggestion} empty="None."/>
      <ReadItems title="Unknowns a developer can check" items={p.unknowns} suggestion={suggestion} empty="None."/></details>}
    </div>)}
   </Section>
   <Section id="dd-facts" title="Known facts" count={v.plan.facts.length} summary="What the sources state, each with its backing.">
    <p className="pt-note" style={{marginTop:0}}>Verified means observed in a repository; reported means someone said it; unconfirmed means hedged or disputed.</p>
    <ReadItems title="" items={v.plan.facts} suggestion={suggestion} empty="No technical facts recorded."/>
   </Section>
   <Section id="dd-people" title="Technical stakeholders" count={v.plan.stakeholders.length} summary="Who is on the team and what the sources say they do.">
    <ul className="pt-people">{v.plan.stakeholders.map(s=><li key={s.id} className="pt-person-row"><span className="pt-person-avatar" aria-hidden="true">{s.name.charAt(0).toUpperCase()}</span>
     <div className="pt-person-main"><p><strong>{s.name}</strong> · {s.role}</p><p className="pt-note" style={{marginTop:2}}>{s.responsibilities||'Responsibility not specified in the sources.'}</p></div></li>)}</ul>
   </Section>
  </>}
 </div>;
}

type Plan=NonNullable<ChampionReview['plan']>;
/** The plan at a glance: goals and milestones in a few lines. */
function PlanOverview({plan,problems,stakeholders}:{plan:Plan;problems:number;stakeholders:number}){
 const title=new Map(plan.milestones.map((m,i)=>[m.id,`${i+1}`]));
 return <section className="pt-card pt-overview" aria-label="Plan at a glance">
  <div className="pt-card-head"><h3>Plan at a glance</h3></div>
  <div className="pt-overview-grid two">
   <div><p className="pt-label">Technical goals</p>{plan.goals.length?<ul className="pt-plain-list">{plan.goals.map(g=><li key={g.id}>{g.text}</li>)}</ul>:<p className="pt-note">None yet.</p>}</div>
   <div><p className="pt-label">Milestones</p>{plan.milestones.length?<ol className="pt-plain-list">{plan.milestones.map(m=><li key={m.id}>{m.title||'Untitled'}<small className="pt-sub">{m.assignee?`Suggested owner: ${m.assignee}`:'No suggested owner · anyone can pick it up'}{m.dependsOn.length?` · after ${m.dependsOn.map(d=>title.get(d)).filter(Boolean).join(', ')}`:''}</small></li>)}</ol>:<p className="pt-note">None yet.</p>}</div>
  </div>
  <p className="pt-note">Based on {problems} engineering problem{problems===1?'':'s'} and {stakeholders} technical stakeholder{stakeholders===1?'':'s'} (under Supporting context). {plan.questions.length} open question{plan.questions.length===1?'':'s'}.</p>
 </section>;
}

/** Each milestone with what it involves, when it's done and what it waits for. */
function MilestoneList({plan}:{plan:Plan}){
 const title=new Map(plan.milestones.map(m=>[m.id,m.title]));
 if(!plan.milestones.length)return <p className="pt-note">No milestones yet.</p>;
 return <ol className="pt-milestones">{plan.milestones.map((m,i)=><li key={m.id} aria-label={`Milestone ${i+1}`}><span className="pt-pill">{i+1}</span><div>
  <strong>{m.title}</strong>
  {m.description&&m.description!==m.title&&<p>{m.description}</p>}
  <p>{m.assignee?`Suggested owner: ${m.assignee}`:'No suggested owner · anyone can pick it up'}{m.system?` · ${m.system}`:''}{m.dependsOn.length?` · after ${m.dependsOn.map(d=>title.get(d)).filter(Boolean).join(', ')}`:''}</p>
  {m.completionCriteria.length>0&&<p>Done when: {m.completionCriteria.join(' · ')}</p>}
 </div></li>)}</ol>;
}

function Status({v}:{v:ChampionReview}){
 const text:Record<ChampionReview['status'],string>={not_submitted:'Chris hasn’t published your team’s onboarding plan yet. It appears here, and for your developers, as soon as he does.',
  revising:'Chris hasn’t published your team’s onboarding plan yet. It appears here, and for your developers, as soon as he does.',
  submitted:'Chris hasn’t published your team’s onboarding plan yet. It appears here, and for your developers, as soon as he does.',
  resubmitted:'Chris hasn’t published your team’s onboarding plan yet. It appears here, and for your developers, as soon as he does.',
  changes_requested:'Chris hasn’t published your team’s onboarding plan yet. It appears here, and for your developers, as soon as he does.',
  approved:`Finalized by ${v.approval?.by} on ${v.approval?new Date(v.approval.at).toLocaleString():''}. Publishing isn’t enabled on this server, so developers don’t see it yet.`,
  published:`Published by ${v.approval?.by} on ${v.approval?new Date(v.approval.at).toLocaleString():''}. Developers can see the plan and choose what to work on.`,
  published_before_dream_day:'Your team’s current onboarding was published by an earlier version of the Portal, before Dream Day.'};
 return <p style={{marginTop:14}} role="status">{text[v.status]}</p>;
}

function History({v}:{v:ChampionReview}){
 return <details className="pt-details"><summary>Plan history ({v.history.length})</summary>
  <ol className="pt-milestones">{v.history.map((e,i)=><li key={i}><span className={'pt-pill '+(e.action==='approved'||e.action==='published'?'green':'blue')}>{e.action.replace('_',' ')}</span>
   <div><strong>{ACTION[e.action]} {e.by}</strong><p>{new Date(e.at).toLocaleString()}</p>{e.comment&&<p style={{whiteSpace:'pre-wrap'}}>“{e.comment}”</p>}</div></li>)}</ol></details>;
}

function ReadItems({title,items,suggestion,empty}:{title:string;items:ReviewItem[];suggestion:string;empty?:string}){
 return <>{title&&<p className="pt-label" style={{marginTop:20}}>{title}</p>}
  {items.length===0?<p className="pt-note">{empty??'None.'}</p>:<ul className="pt-findings">{items.map(x=><li key={x.id}>
   <span style={{display:'flex',gap:6,flexWrap:'wrap'}}><Origin item={x} suggestion={suggestion} viewer="champion"/>{x.status&&<span className={'pt-pill '+STATUS[x.status][1]}>{STATUS[x.status][0]}</span>}</span>
   <span>{x.text}{x.sources?.length?<small>Source: {x.sources.join(', ')}</small>:null}</span></li>)}</ul>}</>;
}
